import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { compileArenaData } from './arena-data.mjs';

const root = new URL('../../../', import.meta.url);
const real = path => readFileSync(new URL(path, root), 'utf8');
const planted = (file, from, to) => path => {
  const text = real(path);
  if (!path.endsWith(file)) return text;
  assert.ok(text.includes(from), `probe did not apply: ${from}`);
  return text.replace(from, to);
};

test('real canon compiles to the committed generator output', () => {
  assert.ok(compileArenaData(real).startsWith('// GENERATED by packages/core/scripts/compile-arena-data.mjs'));
});

test('planted canon prose fails by name instead of compiling a wrong number', () => {
  const trial = 'elder favour 30% (trust of elder) + renown 20%';
  assert.throws(() => compileArenaData(planted('arena-tiers.json', trial, 'elder favour 30% (trust of elder) + legend 10% + renown 10%')), /Unrecognized Trial score authority/);
  assert.throws(() => compileArenaData(planted('arena-tiers.json', trial, 'elder favour 30% (trust of elder) + renown 30%')), /sum to 110%/);
  assert.throws(() => compileArenaData(planted('stats.csv', 'maxHp = 80', 'basemaxHp = 80')), /Missing stat formula vigor\.maxHp/);
  assert.throws(() => compileArenaData(planted('spells-water.csv', 'Rain Needle,projectile 20 m/s,0.00,0.25,3,', 'Rain Needle,projectile 20 m/s,0.00,0.25,,')), /Not a number: bolt mana/);
  assert.throws(() => compileArenaData(planted('spells-water.csv', 'projectile 20 m/s', 'projectile 20 m/s then 30 m/s')), /Unrecognized bolt shape/);
});
